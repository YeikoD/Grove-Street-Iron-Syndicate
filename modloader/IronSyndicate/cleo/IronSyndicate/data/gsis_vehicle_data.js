// Función helper para obtener capacidad de baúl por ID de modelo
export function getVehicleTrunkCapacity(modelId) {
    var vehicle = VEHICLE_DATA.find(function(v) { return v.id === modelId; });
    return vehicle ? vehicle.trunkCapacity : 150; // Default 150kg si no se encuentra
}

// Función helper para obtener nombre del vehículo por ID
export function getVehicleName(modelId) {
    var vehicle = VEHICLE_DATA.find(function(v) { return v.id === modelId; });
    return vehicle ? vehicle.name : "Unknown";
}
